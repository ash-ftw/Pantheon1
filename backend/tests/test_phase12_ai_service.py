def test_extract_json_dict_formats():
    """Verify JSON extraction handles raw JSON, markdown code blocks, and embedded objects."""
    # 1. Pure raw JSON
    raw = '{"name": "test", "concurrency": 10}'
    assert AIService._extract_json_dict(raw) == {"name": "test", "concurrency": 10}

    # 2. Markdown fenced code block
    fenced = """Here is the scenario definition:
```json
{
  "name": "SQL Injection Test",
  "category": "sql_injection",
  "concurrency": 5
}
```
Hope this helps!"""
    assert AIService._extract_json_dict(fenced) == {
        "name": "SQL Injection Test",
        "category": "sql_injection",
        "concurrency": 5,
    }

    # 3. Embedded JSON inside thoughts
    embedded = 'I will formulate this response: {"target": "/api/login", "method": "POST"} - end of thoughts.'
    assert AIService._extract_json_dict(embedded) == {"target": "/api/login", "method": "POST"}


@pytest.mark.asyncio
async def test_stream_chat_reasoning_and_content():
    """Test stream_chat splits reasoning deltas and content deltas."""
    service = AIService(api_key="mock-key", base_url="https://mock.api/v1")

    # Mock chunk structure from OpenAI SDK
    chunk1 = MagicMock()
    chunk1.choices = [MagicMock()]
    chunk1.choices[0].delta = MagicMock(reasoning_content="Thinking step 1...", content=None)

    chunk2 = MagicMock()
    chunk2.choices = [MagicMock()]
    chunk2.choices[0].delta = MagicMock(reasoning_content=None, content="Final answer text.")

    async def mock_generator():
        yield chunk1
        yield chunk2

    mock_client = MagicMock()
    mock_client.chat.completions.create = AsyncMock(return_value=mock_generator())

    with patch.object(service, "get_client", return_value=mock_client):
        chunks = []
        async for item in service.stream_chat(
            messages=[{"role": "user", "content": "Test prompt"}],
            enable_thinking=True,
        ):
            chunks.append(item)

        reasoning_chunks = [c for c in chunks if c["type"] == "reasoning"]
        content_chunks = [c for c in chunks if c["type"] == "content"]
        done_chunks = [c for c in chunks if c["type"] == "done"]

        assert len(reasoning_chunks) == 1
        assert reasoning_chunks[0]["delta"] == "Thinking step 1..."
        assert len(content_chunks) == 1
        assert content_chunks[0]["delta"] == "Final answer text."
        assert len(done_chunks) == 1
        assert done_chunks[0]["reasoning"] == "Thinking step 1..."
        assert done_chunks[0]["content"] == "Final answer text."



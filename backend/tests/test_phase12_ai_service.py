@pytest.mark.asyncio
async def test_ai_scenario_service_generation_and_fallback():
    """Verify ai_scenario_service tries AI first and falls back safely on error."""
    org_id = uuid4()
    req = AIGenerateScenarioRequest(
        prompt="Simulate SQL injection against our search endpoint",
        category=ScenarioCategory.SQLI_RESILIENCE,
        target_path="/api/search",
    )

    # 1. Successful AI generation
    valid_scenario = ScenarioDefinition(
        name="AI SQLi Attack",
        description="Auto-generated SQLi",
        category=ScenarioCategory.SQLI_RESILIENCE,
        target=ScenarioTarget(path="/api/search", port=8080),
        method="GET",
        payload_category="sqli_resilience",
        parameters={"parameter_name": "q"},
        concurrency=12,
        duration=30,
        expected_signals=["SQL Syntax Error"],
        estimated_impact=EstimatedImpact.MEDIUM,
        source=ScenarioSource.AI,
    )

    with patch(
        "app.services.ai_scenario_service.ai_service.generate_structured",
        new=AsyncMock(return_value=(valid_scenario, "Thought about SQL injection vectors")),
    ):
        result = await generate_scenario(req, org_id)
        assert result.category == ScenarioCategory.SQLI_RESILIENCE
        assert result.source == ScenarioSource.AI
        assert result.concurrency == 12

    # 2. Failing AI generation triggers robust rule-based fallback
    with patch(
        "app.services.ai_scenario_service.ai_service.generate_structured",
        new=AsyncMock(side_effect=RuntimeError("NVIDIA NIM API timeout")),
    ):
        fallback_result = await generate_scenario(req, org_id)
        assert fallback_result is not None
        assert fallback_result.category == ScenarioCategory.SQLI_RESILIENCE
        assert fallback_result.source == ScenarioSource.AI
        assert fallback_result.target.path == "/api/search"


@pytest.mark.asyncio
async def test_ai_status_endpoint():
    """Verify GET /api/ai/status endpoint returns proper provider metadata."""
    org_id = uuid4()
    user_id = uuid4()
    token = create_access_token(
        user_id=user_id,
        email="security@pantheon.local",
        org_id=org_id,
        role="Admin",
    )

    # Mock get_current_user to avoid database hits during unit testing
    from app.services.auth_service import get_current_user

    test_user = User(
        id=user_id,
        email="security@pantheon.local",
        full_name="AI Security Engineer",
        hashed_password="hash",
        org_id=org_id,
        role="Admin",
        is_active=True,
    )
    app.dependency_overrides[get_current_user] = lambda: test_user

    try:
        transport = ASGITransport(app=app)
        async with AsyncClient(transport=transport, base_url="http://test") as client:
            response = await client.get(
                "/api/ai/status",
                headers={"Authorization": f"Bearer {token}"},
            )
            assert response.status_code == 200
            data = response.json()
            assert data["provider"] == "nvidia_nim"
            assert data["model"] == "nvidia/nemotron-3.5-lightning-30b-a3b"
            assert data["thinking_enabled"] is True
            assert data["configured"] is True
    finally:
        app.dependency_overrides.pop(get_current_user, None)
